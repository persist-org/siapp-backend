-- Phase 04.1: uploaded photos. One row per photo a person registers for upload; the bytes live
-- in object storage (or on the server's disk) under storage_key, never in the database.
--
-- The flow has two states. A photo is PENDING from POST /media until the owner confirms it with
-- POST /media/{id}/complete, which checks the object really is there (size and type), and then
-- it is UPLOADED and may be attached to a record (Phase 04.2, attached_entity_*). A PENDING row,
-- or one that is never attached, is removed with its object by the cleanup job.
CREATE TYPE media_purpose AS ENUM (
    'PROFILE_PHOTO', 'ATTENDANCE_SELFIE', 'REPORT', 'INSTRUCTION',
    'PATROL_SCAN', 'PANIC_REPORT', 'ASSET_REPORT', 'EMEMO');

CREATE TYPE media_status AS ENUM ('PENDING', 'UPLOADED');

-- Where the picture came from. The selfie check-in only accepts CAMERA (manual §3.2.3.1: the
-- photo may only be taken directly); the field is evidence, not a rule of this table.
CREATE TYPE capture_source AS ENUM ('CAMERA', 'GALLERY', 'UNKNOWN');

-- ⚠ No storage driver column, on purpose. One environment uses one storage, so every key means
-- the same thing everywhere in the table. Moving between drivers (local to S3, MinIO to AWS) is
-- a copy of the objects under the SAME keys, done by the operator; nothing here changes. A
-- per-row driver would only invite a half-migrated state that no code is written to read.
CREATE TABLE media (
    id                   BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    organization_id      BIGINT NOT NULL DEFAULT current_setting('app.current_org')::bigint
                         REFERENCES organizations(id),
    owner_personnel_id   BIGINT NOT NULL REFERENCES personnels(id),
    purpose              media_purpose NOT NULL,
    -- What the owner declared at registration. complete compares the stored object with these.
    content_type         TEXT NOT NULL,
    size_bytes           BIGINT NOT NULL,
    -- {organization_id}/{purpose}/{yyyy}/{mm}/{id}-{random}. Generated by the server only, and
    -- its id part is this row's id: the id is taken from the sequence before the insert.
    storage_key          TEXT NOT NULL,
    status               media_status NOT NULL DEFAULT 'PENDING',
    -- Capture metadata (anti-fraud evidence). Nullable: a gallery picture or an old phone may
    -- not know them.
    captured_at          timestamptz,
    capture_latitude     numeric(9,6),
    capture_longitude    numeric(9,6),
    capture_source       capture_source NOT NULL,
    -- Set by Attach (Phase 04.2), which is also what stops a second record from attaching the
    -- same photo.
    attached_entity_type TEXT,
    attached_entity_id   BIGINT,
    created_at           timestamptz NOT NULL DEFAULT now(),
    updated_at           timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT media_size_check CHECK (size_bytes > 0),
    CONSTRAINT media_capture_latitude_check CHECK (capture_latitude BETWEEN -90 AND 90),
    CONSTRAINT media_capture_longitude_check CHECK (capture_longitude BETWEEN -180 AND 180),
    -- A position is both coordinates or neither.
    CONSTRAINT media_capture_position_check CHECK ((capture_latitude IS NULL) = (capture_longitude IS NULL)),
    -- An attachment is both its type and its id or neither.
    CONSTRAINT media_attachment_check CHECK ((attached_entity_type IS NULL) = (attached_entity_id IS NULL))
);

-- A key is never handed out twice. The id inside it already makes that so; the index makes it a
-- fact the database enforces, and serves a lookup by key.
CREATE UNIQUE INDEX media_storage_key_key ON media (organization_id, storage_key);
-- The cleanup job walks the rows that are still PENDING, or old, per organization.
CREATE INDEX media_status_created_idx ON media (organization_id, status, created_at);

ALTER TABLE media ENABLE ROW LEVEL SECURITY;
ALTER TABLE media FORCE ROW LEVEL SECURITY;
CREATE POLICY org_isolation ON media
    USING (organization_id = NULLIF(current_setting('app.current_org', true), '')::bigint)
    WITH CHECK (organization_id = NULLIF(current_setting('app.current_org', true), '')::bigint);
GRANT SELECT, INSERT, UPDATE, DELETE ON media TO siapp_app;
-- Registering takes the id with nextval() BEFORE the insert, because the storage key contains
-- it. An insert alone needs no sequence right (the identity sequence is the table's own), but
-- calling nextval() directly does.
GRANT USAGE ON SEQUENCE media_id_seq TO siapp_app;

-- +goose Down
DROP TABLE media;
DROP TYPE capture_source;
DROP TYPE media_status;
DROP TYPE media_purpose;
