// LocalStorage keeps photos on the disk of whatever machine the API runs on, with no extra
// service. On a laptop that is a folder of the project (make run); on a server it is a folder
// of that server, mounted into the containers. The code and the settings have the same shape
// in both: only STORAGE_LOCAL_DIR and MEDIA_PUBLIC_BASE_URL differ.
//
// ⚠ Deployment rule: the API and the worker must see the SAME directory, because the worker's
// media:cleanup job deletes through this driver. That means one host, or a volume shared by
// both containers. Nothing replicates the directory, so backing it up is the operator's job.
//
// There are no presigned URLs here, so the driver makes its own: PresignPut and PresignGet
// return {MEDIA_PUBLIC_BASE_URL}/api/v1/media/blobs/{token}, and the blob routes (blobs.go)
// serve them. The token is a credential for as long as it lives.
type LocalStorage struct {
	// root is the absolute directory every object lives under.
	root    string
	key     []byte
	baseURL string
	clock   clock.Clock
}

var _ Storage = (*LocalStorage)(nil)

// NewLocal creates the storage directory if it is missing and proves it can be written to, so
// that an unwritable directory fails the boot and not the first upload.
func NewLocal(cfg config.Storage, clk clock.Clock) (*LocalStorage, error) {
	if len(cfg.LocalSigningKey) < 32 {
		return nil, errors.New("local storage: the signing key must be at least 32 bytes")
	}
	if cfg.PublicBaseURL == "" {
		return nil, errors.New("local storage: MEDIA_PUBLIC_BASE_URL is empty")
	}
	root, err := filepath.Abs(cfg.LocalDir)
	if err != nil {
		return nil, fmt.Errorf("local storage: resolve %q: %w", cfg.LocalDir, err)
	}
	l := &LocalStorage{
		root:    root,
		key:     []byte(cfg.LocalSigningKey),
		baseURL: strings.TrimRight(cfg.PublicBaseURL, "/"),
		clock:   clk,
	}
	if err := os.MkdirAll(l.root, 0o750); err != nil {
		return nil, fmt.Errorf("local storage: create %s: %w", l.root, err)
	}
	if err := l.probe(); err != nil {
		return nil, fmt.Errorf("local storage: %s is not writable: %w", l.root, err)
	}
	return l, nil
}

// probe writes a file and deletes it again.
func (l *LocalStorage) probe() error {
	f, err := os.CreateTemp(l.root, ".probe-*")
	if err != nil {
		return err
	}
	name := f.Name()
	_, writeErr := f.WriteString("ok")
	closeErr := f.Close()
	removeErr := os.Remove(name)
	return errors.Join(writeErr, closeErr, removeErr)
}

// path returns the file of key.
//
// ⚠ This is what stops path traversal. Keys are generated by the server and never come from a
// client, and the key pattern already allows no "..", but a bug elsewhere (a key built from
// the wrong field, a pattern loosened later) must not turn into a read or write outside the
// root. So the resolved path is checked as well: it has to stay under root, by filepath.Rel.
func (l *LocalStorage) path(key string) (string, error) {
	if !ValidKey(key) {
		return "", ErrInvalidKey
	}
	full := filepath.Join(l.root, filepath.FromSlash(key))
	rel, err := filepath.Rel(l.root, full)
	if err != nil || !filepath.IsLocal(rel) {
		return "", ErrInvalidKey
	}
	return full, nil
}

// blobOp is what a token allows. A put token cannot read and a get token cannot write: the
// operation is inside the signed bytes.
type blobOp string

const (
	opPut blobOp = "put"
	opGet blobOp = "get"
)

// blobClaims is what a token says. Every field is inside the HMAC.
type blobClaims struct {
	Op          blobOp `json:"o"`
	Key         string `json:"k"`
	ContentType string `json:"t"`
	// MaxBytes is the most a put may carry (the declared size); 0 for a get.
	MaxBytes int64 `json:"s"`
	// Expires is a Unix time in seconds.
	Expires int64 `json:"e"`
}

// macContext separates these HMACs from any other use of the same bytes.
const macContext = "siapp media blob v1\n"

var (
	errTokenInvalid = errors.New("media: blob token is invalid")
	errTokenExpired = errors.New("media: blob token has expired")
)

var tokenEncoding = base64.RawURLEncoding

func (l *LocalStorage) mac(payload []byte) []byte {
	h := hmac.New(sha256.New, l.key)
	h.Write([]byte(macContext))
	h.Write(payload)
	return h.Sum(nil)
}

// sign returns payload.mac, both base64url: only characters a URL path carries as they are.
// The payload is the claims themselves, so the URL is all the server needs to know what it
// allows, and nothing is stored.
func (l *LocalStorage) sign(c blobClaims) string {
	payload, err := json.Marshal(c)
	if err != nil {
		// A struct of strings and integers cannot fail to marshal.
		panic("media: marshal blob claims: " + err.Error())
	}
	return tokenEncoding.EncodeToString(payload) + "." + tokenEncoding.EncodeToString(l.mac(payload))
}

// verify checks a token and returns its claims. The signature is compared in constant time and
// is judged before anything inside the payload is trusted, including the expiry.
func (l *LocalStorage) verify(token string, want blobOp) (blobClaims, error) {
	if token == "" || len(token) > maxTokenLength {
		return blobClaims{}, errTokenInvalid
	}
	encodedPayload, encodedMAC, found := strings.Cut(token, ".")
	if !found {
		return blobClaims{}, errTokenInvalid
	}
	payload, err := tokenEncoding.DecodeString(encodedPayload)
	if err != nil {
		return blobClaims{}, errTokenInvalid
	}
	got, err := tokenEncoding.DecodeString(encodedMAC)
	if err != nil || !hmac.Equal(got, l.mac(payload)) {
		return blobClaims{}, errTokenInvalid
	}

	var c blobClaims
	dec := json.NewDecoder(bytes.NewReader(payload))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&c); err != nil {
		return blobClaims{}, errTokenInvalid
	}
	// The token is ours, yet it must still be one a current build would have made.
	if c.Op != want || !ValidKey(c.Key) || c.ContentType == "" {
		return blobClaims{}, errTokenInvalid
	}
	if !l.clock.Now().Before(time.Unix(c.Expires, 0)) {
		return blobClaims{}, errTokenExpired
	}
	return c, nil
}

func (l *LocalStorage) url(c blobClaims) string { return l.baseURL + BlobPath + l.sign(c) }

// PresignPut returns the blob URL a client PUTs the bytes to. The signed content type must be
// sent as the Content-Type header, and the body may not exceed the declared size.
func (l *LocalStorage) PresignPut(_ context.Context, key string, in PutInput) (Upload, error) {
	if _, err := l.path(key); err != nil {
		return Upload{}, err
	}
	if in.ContentType == "" || in.SizeBytes < 1 || in.TTL <= 0 {
		return Upload{}, errors.New("local storage: a put needs a content type, a size and a lifetime")
	}
	expires := time.Unix(l.clock.Now().Add(in.TTL).Unix(), 0).UTC()
	return Upload{
		URL:       l.url(blobClaims{Op: opPut, Key: key, ContentType: in.ContentType, MaxBytes: in.SizeBytes, Expires: expires.Unix()}),
		Method:    http.MethodPut,
		Headers:   map[string]string{"Content-Type": in.ContentType},
		ExpiresAt: expires,
	}, nil
}

// PresignGet returns the blob URL that serves the object with the given content type.
func (l *LocalStorage) PresignGet(_ context.Context, key, contentType string, ttl time.Duration) (string, error) {
	if _, err := l.path(key); err != nil {
		return "", err
	}
	if contentType == "" || ttl <= 0 {
		return "", errors.New("local storage: a get needs a content type and a lifetime")
	}
	return l.url(blobClaims{Op: opGet, Key: key, ContentType: contentType, Expires: l.clock.Now().Add(ttl).Unix()}), nil
}

// open opens the object of key for reading. A key with no file, or whose file is a directory,
// is ErrObjectNotFound.
func (l *LocalStorage) open(key string) (*os.File, os.FileInfo, error) {
	full, err := l.path(key)
	if err != nil {
		return nil, nil, err
	}
	f, err := os.Open(full) //nolint:gosec // G304: full comes from path(), which keeps it under root
	if err != nil {
		if errors.Is(err, os.ErrNotExist) {
			return nil, nil, ErrObjectNotFound
		}
		return nil, nil, fmt.Errorf("open object: %w", err)
	}
	info, err := f.Stat()
	if err != nil {
		_ = f.Close()
		return nil, nil, fmt.Errorf("stat object: %w", err)
	}
	if info.IsDir() {
		_ = f.Close()
		return nil, nil, ErrObjectNotFound
	}
	return f, info, nil
}

// Head returns the size from the file and the type from its first 512 bytes
// (http.DetectContentType), never from what the client claimed: a text file uploaded as
// image/jpeg is reported as text, and complete refuses it.
func (l *LocalStorage) Head(_ context.Context, key string) (Object, error) {
	f, info, err := l.open(key)
	if err != nil {
		return Object{}, err
	}
	defer func() { _ = f.Close() }()

	head := make([]byte, sniffBytes)
	n, err := io.ReadFull(f, head)
	if err != nil && !errors.Is(err, io.ErrUnexpectedEOF) && !errors.Is(err, io.EOF) {
		return Object{}, fmt.Errorf("read object: %w", err)
	}
	return Object{SizeBytes: info.Size(), ContentType: http.DetectContentType(head[:n])}, nil
}

// Delete removes the object. A file that is already gone is not an error, like S3.
func (l *LocalStorage) Delete(_ context.Context, key string) error {
	full, err := l.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(full); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("delete object: %w", err)
	}
	return nil
}

// store writes body as the object of key.
//
// ⚠ The bytes go to a temporary file in the same directory, are fsynced, and only then
// renamed onto the key. Why: rename within one directory is atomic, so the key either has the
// whole previous content or the whole new one. An upload that is cut off halfway (the phone
// loses signal, the request is aborted, the body hits its size cap) fails in the copy, the
// temporary file is removed and the key was never touched, so there is no partial object that
// complete could mistake for a finished photo. The temporary file is in the same directory
// because rename does not work across file systems.
func (l *LocalStorage) store(key string, body io.Reader) (err error) {
	full, err := l.path(key)
	if err != nil {
		return err
	}
	dir := filepath.Dir(full)
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return fmt.Errorf("create directory: %w", err)
	}
	tmp, err := os.CreateTemp(dir, TempFilePrefix+"*")
	if err != nil {
		return fmt.Errorf("create temp file: %w", err)
	}
	committed := false
	defer func() {
		if !committed {
			_ = tmp.Close()
			_ = os.Remove(tmp.Name())
		}
	}()

	if _, err := io.Copy(tmp, body); err != nil {
		return err
	}
	if err := tmp.Sync(); err != nil {
		return fmt.Errorf("sync temp file: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return fmt.Errorf("close temp file: %w", err)
	}
	if err := os.Rename(tmp.Name(), full); err != nil {
		return fmt.Errorf("rename temp file: %w", err)
	}
	committed = true
	syncDir(dir)
	return nil
}

// syncDir makes the rename itself durable. Best effort: not every file system allows it, and
// the file is already complete either way.
func syncDir(dir string) {
	d, err := os.Open(dir) //nolint:gosec // G304: dir is the parent of a path that path() vetted
	if err != nil {
		return
	}
	_ = d.Sync()
	_ = d.Close()
}
